def extract_topic_sectors(
    text: str,
    *,
    summary: str = "",
    title_weight: float = 1.0,
    body_weight: float = 0.5,
    keywords: dict[str, list[str]] = TOPIC_KEYWORDS,
) -> list[SectorTag]:
    """주제어 사전으로 뉴스 텍스트 → 섹터 태그(정본 22). stock_codes 는 비어 있음.

    제목 매칭은 가중치 높게(title_weight), 요약/본문은 낮게(body_weight) 합산 후
    최대값 기준 0~1 정규화. 매칭 없으면 빈 리스트(거시 외 일반 뉴스).
    """
    bucket: dict[str, float] = {}
    for src, weight in ((text, title_weight), (summary, body_weight)):
        if not src:
            continue
        for kw, sectors in keywords.items():
            if kw in src:
                for sec in sectors:
                    bucket[sec] = bucket.get(sec, 0.0) + weight

    if not bucket:
        return []

    max_raw = max(bucket.values())
    tags = [
        SectorTag(sector=sec, score=raw / max_raw, stock_codes=[])
        for sec, raw in bucket.items()
    ]
    tags.sort(key=lambda t: (-t.score, t.sector))
    return tags
